import { test, expect } from "@playwright/test";
import { mkdirSync, readFileSync } from "node:fs";
import { createRequire } from "node:module";
import { verifyAuditPackage } from "../.testbuild/workbench/audit-package.js";
const axe = readFileSync(createRequire(import.meta.url).resolve("axe-core/axe.min.js"), "utf8");
const artifacts = process.env.AGENTICK_UI_ARTIFACTS ?? "test-results/analyst-screenshots";
mkdirSync(artifacts, { recursive: true });
async function identity(page, actor) {
  if (!(await page.locator(".account-popover").isVisible())) await page.locator(".console-account > summary").click();
  await page.locator("#identity").selectOption(actor);
}
test("saved analyst request, real trace, limited county and independent pending review", async ({ page }) => {
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/#/analyst");
  await expect(page.getByRole("heading", { name: "Public data analyst", exact: true })).toBeVisible();
  await expect(page.getByText("No analyst requests yet.", { exact: false })).toBeVisible();
  await page.getByText("Read tools and boundaries", { exact: true }).click();
  await expect(page.locator(".analyst-page")).toContainText("No write tools");
  await page.getByRole("button", { name: "Open services", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(page.locator("#workspace-navigation")).toBeVisible();
  await expect(page.locator(".service-group h3")).toHaveText(["Work", "Build", "Data", "Administration"]);
  await page.keyboard.press("Escape");
  await expect(page.getByRole("button", { name: "Open services", exact: true })).toBeFocused();
  expect(await page.getByRole("button", { name: "Open services", exact: true }).evaluate(element => getComputedStyle(element).outlineStyle)).not.toBe("none");
  await page.getByLabel("County (optional)").fill("Montgomery");
  await page.getByLabel("Question", { exact: true }).fill("Which declaration covers the county in the saved sample?");
  await page.route("**/api/analyst", async route => {
    await route.fulfill({ status: 503, contentType: "application/json", body: JSON.stringify({ error: "Temporary analyst outage. Retry this request." }) });
  }, { times: 1 });
  await page.getByRole("button", { name: "Run agent", exact: true }).click();
  await expect(page.locator("#notice")).toContainText("Temporary analyst outage");
  await expect(page.getByLabel("County (optional)")).toHaveValue("Montgomery");
  await expect(page.getByLabel("Question", { exact: true })).toHaveValue("Which declaration covers the county in the saved sample?");
  await page.getByRole("button", { name: "Run agent", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Execution: completed", exact: true })).toBeVisible();
  const url = page.url();
  await expect(page.locator(".analyst-trace > li")).toHaveCount(3);
  await expect(page.locator(".analyst-trace")).toContainText("get_ontology_object");
  await expect(page.locator(".analyst-source")).toContainText("5 county rows · 1 distinct declaration");
  await page.getByText("Exact saved source", { exact: true }).click();
  await expect(page.locator(".analyst-source pre")).toContainText("DisasterDeclarationsSummaries");
  await page.getByText("Exact saved source", { exact: true }).click();
  await expect(page.locator(".analyst-columns")).toContainText("Montgomery (County) appears under declaration #3631");
  await page.reload();
  await expect(page.getByRole("heading", { name: "Execution: completed", exact: true })).toBeVisible();
  expect(page.url()).toBe(url);
  for (const width of [1440, 1024, 768, 390]) {
    await page.setViewportSize({ width, height: 1000 });
    await page.evaluate(() => scrollTo(0, 0));
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), `overflow at ${width}`).toBe(true);
    await expect(page.getByRole("link", { name: "Review output", exact: true })).toBeVisible();
    await page.screenshot({ path: `${artifacts}/after-${width}.png`, fullPage: true });
  }
  await page.evaluate(axe);
  const accessibility = await page.evaluate(() => window.axe.run(document, { runOnly: { type: "tag", values: ["wcag2a", "wcag2aa", "wcag21aa"] } }));
  expect(accessibility.violations).toEqual([]);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("link", { name: "Review output", exact: true }).click();
  await expect(page.locator("[data-output-review]")).toBeVisible();
  await page.getByRole("button", { name: "Submit for review", exact: true }).click();
  await expect(page.locator("#work-progress")).toContainText("0 of 2");
  await expect(page.getByRole("button", { name: "Approve this handoff", exact: true })).toHaveCount(0);
  const runId = new URL(page.url()).hash.split("/").at(-1);
  const snapshot = await (await page.request.get("/api/workspace", { headers: { authorization: "Bearer demo.operator" } })).json();
  const run = snapshot.pipelines.runs.find(run => run.id === runId);
  const denied = await page.request.post("/api/pipeline", { headers: { authorization: "Bearer demo.operator" }, data: { action: "approve", runId, expectedRevision: run.revision } });
  expect(denied.status()).toBe(403);
  await identity(page, "demo.reviewer-one");
  await page.getByRole("button", { name: "Approve this handoff", exact: true }).click();
  await expect(page.locator("#work-progress")).toContainText("1 of 2");
  await page.screenshot({ path: `${artifacts}/pending-independent-review.png`, fullPage: true });
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("link", { name: "JSON", exact: true }).click();
  const download = await downloadPromise;
  await download.saveAs(`${artifacts}/pending-audit.json`);
  const pkg = JSON.parse(readFileSync(await download.path(), "utf8"));
  expect(verifyAuditPackage(pkg).ok).toBe(true);
  expect(pkg.stages[0].approvals).toEqual(["demo.reviewer-one"]);
  expect(pkg.stages[0].status).toBe("awaiting_review");
  pkg.stages[0].output += "Tampered";
  expect(verifyAuditPackage(pkg).ok).toBe(false);
  await identity(page, "demo.operator");
  await page.goto("/#/analyst");
  await page.getByLabel("County (optional)").fill("Fairfax");
  await page.getByLabel("Question", { exact: true }).fill("Does the saved sample establish that Fairfax was unaffected?");
  await page.getByRole("button", { name: "Run agent", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Execution: completed · limited source", exact: true })).toBeVisible();
  await expect(page.locator(".analyst-trace > li")).toHaveCount(2);
  await expect(page.locator(".analyst-columns")).toContainText("does not establish that the county was unaffected");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${artifacts}/limited-county.png` });
  expect(errors).toEqual([]);
});
